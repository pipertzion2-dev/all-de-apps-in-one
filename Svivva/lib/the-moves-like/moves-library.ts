export function getMove(id: string): DanceMove | undefined {
  return MOVES_LIBRARY.find((m) => m.id === id);
}

export function filterMoves(opts: {
  style?: DanceStyle | "all";
  level?: SkillLevel | "all";
  energy?: EnergyLevel | "all";
  query?: string;
}): DanceMove[] {
  const q = opts.query?.trim().toLowerCase() ?? "";
  return MOVES_LIBRARY.filter((m) => {
    if (opts.style && opts.style !== "all" && m.style !== opts.style) return false;
    if (opts.level && opts.level !== "all" && m.level !== opts.level) return false;
    if (opts.energy && opts.energy !== "all" && m.energy !== opts.energy) return false;
    if (!q) return true;
    return (
      m.name.toLowerCase().includes(q) || m.tags.some((t) => t.includes(q)) || m.style.includes(q)
    );
  });
}

